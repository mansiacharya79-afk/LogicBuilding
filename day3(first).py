''''Program to Calculate the Square and Cube of a Number:
Write a program where the user enters a number, and the program calculates its square and cube, and then prints the results.'''




num=int(input("Enter a number: "))
print(f"The square of the number {num} is: {num**2}")
print(f"the cube of the number {num} is :{num**3}")



'''Output:
Enter a number: 5
The square of the number 5 is: 25
the cube of the number 5 is :125'''