'''Write a Python program to get the keys and values of a dictionary separately.'''


data={"name":"mansi","age":21,"clg":"NMAMIT"}
keys=list(data.keys())
values=list(data.values())
print("Keys:", keys)
print("Values:", values)


'''output
Keys: ['name', 'age', 'clg']
Values: ['mansi', 21, 'NMAMIT']
'''